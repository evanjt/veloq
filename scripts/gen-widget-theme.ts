function androidNight(): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GEN} -->
<resources>
${androidColors(widgetPalette.dark)}
  <color name="widget_record_grad_start">${widgetRecord.dark.gradientStart}</color>
  <color name="widget_record_grad_end">${widgetRecord.dark.gradientEnd}</color>
  <color name="widget_record_accent">${widgetRecord.dark.accent}</color>
</resources>
`;
}

// From Android 12 the launcher owns the widget corner, so the radii alias its own dimens there and
// the fixed tokens above stay the fallback below it.
function androidV31(): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GEN} -->
<resources>
  <dimen name="widget_radius">@android:dimen/system_app_widget_background_radius</dimen>
  <dimen name="widget_radius_inner">@android:dimen/system_app_widget_inner_radius</dimen>
</resources>
`;
}

// The launcher shortcut icons are drawn by the widget module, which compiles as its own library
// and cannot name the app's colours, so it carries these two. The brand fill with the ink the
// palette puts on it, as on the app's primary button.
function androidShortcuts(): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GEN} -->
<resources>
  <color name="veloq_shortcut_background">${widgetPalette.light.primary}</color>
  <color name="veloq_shortcut_glyph">${widgetPalette.light.textOnPrimary}</color>
</resources>
`;
}

/**
 * `--check` compares instead of writing, so the gate can say the committed
 * files are behind the palette. The drift that prompted it went unnoticed
 * because the generator could not run at all.
 */
const CHECK = process.argv.includes('--check');
const stale: string[] = [];

function emit(rel: string, contents: string): void {
  const abs = join(ROOT, rel);
  if (CHECK) {
    if (trackedText(ROOT, rel) !== contents) stale.push(rel);
    return;
  }
  mkdirSync(join(abs, '..'), { recursive: true });
  writeFileSync(abs, contents);

  console.log(`  wrote ${rel}`);
}

// Canonical tracked location. The config plugins copy these into the prebuilt
// ios/ and android/ projects (both gitignored, regenerated by `expo prebuild`).
emit('widget/ios/VeloqWidget/WidgetTheme.swift', iosFile());
emit('widget/android/res/values/widget_theme.xml', androidLight());
emit('widget/android/res/values-night/widget_theme.xml', androidNight());
emit('widget/android/res/values-v31/widget_theme.xml', androidV31());
emit('modules/veloq-widget/android/src/main/res/values/shortcut_theme.xml', androidShortcuts());

if (CHECK) {
  if (stale.length > 0) {
    console.error(
      `The committed widget theme is behind the palette: ${stale.length} file(s).\n` +
        'The widget draws its placeholder chrome from these, so it is showing the old token.\n' +
        'Run `npm run gen:widget-theme` and commit what it writes.\n'
    );
    for (const rel of stale) console.error(`  ${rel}`);
    process.exit(1);
  }
  console.log('Widget theme guard: the committed files match the palette.');
} else {
  console.log('widget theme generated.');
}
