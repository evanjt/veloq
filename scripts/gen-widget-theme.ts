/**
 * Generates the committed native widget theme files from the single TS source of
 * truth (`src/shared/theme/widgetTheme.ts`, itself derived from `src/theme/colors.ts`).
 *
 * Widget native code (Swift WidgetKit / Android RemoteViews) cannot import the app
 * theme, so the static chrome it renders before any snapshot exists must read these
 * generated constants. The dynamic, data-driven colours come from the snapshot's
 * `theme` block at render time; these files cover the placeholder/default state.
 *
 * Run: `npm run gen:widget-theme`. The emitted files carry a GENERATED header and must
 * never be hand-edited; change `colors.ts`/`widgetTheme.ts` and regenerate instead.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { trackedText } from './lib/indexedSources.mjs';

import {
  widgetBody,
  widgetChart,
  widgetFace,
  widgetLayout,
  widgetPalette,
  widgetRecord,
  widgetTextScale,
  widgetType,
  type WidgetPalette,
} from '@/shared/theme/widgetTheme';

const ROOT = join(__dirname, '..');
const GEN = 'GENERATED by scripts/gen-widget-theme.ts. Do not edit. Run: npm run gen:widget-theme';

/** The palette fields that hold one colour, as against the ramp. */
type ColourKey = {
  [K in keyof WidgetPalette]: WidgetPalette[K] extends string ? K : never;
}[keyof WidgetPalette];

// Order the palette fields once so Swift and XML stay aligned.
const PALETTE_KEYS: ColourKey[] = [
  'background',
  'surface',
  'textPrimary',
  'textSecondary',
  'primary',
  'textOnPrimary',
  'gold',
  'blue',
  'fatigue',
  'chartFitness',
  'chartFatigue',
  'formHighRisk',
  'formOptimal',
  'formGreyZone',
  'formFresh',
  'formTransition',
  'trendUp',
  'trendDown',
  'trendFlat',
  'warning',
  'toneNegative',
  'toneCaution',
  'tonePositive',
  'toneNeutral',
  'toneRecord',
  'toneInfo',
  'toneOpportunity',
  'border',
  'bodyFill',
];

const STEPS = Object.keys(widgetType) as (keyof typeof widgetType)[];

const snake = (k: string) => k.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);

// The palette stores alpha hex as #RRGGBBAA (RN/SwiftUI order); Android XML wants #AARRGGBB.
const androidHex = (hex: string) => (hex.length === 9 ? `#${hex.slice(7)}${hex.slice(1, 7)}` : hex);

function swiftPalette(name: string, p: WidgetPalette): string {
  const lines = PALETTE_KEYS.map((k) => `    static let ${k} = Color(hex: "${p[k]}")`);
  const ramp = p.strengthRamp.map((hex) => `Color(hex: "${hex}")`).join(', ');
  lines.push(`    static let strengthRamp = [${ramp}]`);
  return `  enum ${name} {\n${lines.join('\n')}\n  }`;
}

function iosFile(): string {
  return `// ${GEN}
import SwiftUI

/// Static widget palette + metrics. Dynamic colours come from the snapshot \`theme\`
/// block; this is the placeholder/default chrome before a snapshot lands.
enum WidgetTheme {
${swiftPalette('Light', widgetPalette.light)}

${swiftPalette('Dark', widgetPalette.dark)}

  enum Record {
    enum Light {
      static let gradientStart = Color(hex: "${widgetRecord.light.gradientStart}")
      static let gradientEnd = Color(hex: "${widgetRecord.light.gradientEnd}")
      static let accent = Color(hex: "${widgetRecord.light.accent}")
    }

    enum Dark {
      static let gradientStart = Color(hex: "${widgetRecord.dark.gradientStart}")
      static let gradientEnd = Color(hex: "${widgetRecord.dark.gradientEnd}")
      static let accent = Color(hex: "${widgetRecord.dark.accent}")
    }

    static let foreground = Color(hex: "${widgetRecord.foreground}")

    /// The record tone for the scheme a view is drawn in.
    static func accent(_ scheme: ColorScheme) -> Color {
      scheme == .dark ? Dark.accent : Light.accent
    }
  }

  enum Layout {
    static let radius: CGFloat = ${widgetLayout.radius}
    static let radiusInner: CGFloat = ${widgetLayout.radiusInner}
    static let padding: CGFloat = ${widgetLayout.padding}
    static let gap: CGFloat = ${widgetLayout.gap}
    static let heroLine: CGFloat = ${widgetLayout.heroLine}
    static let metricLine: CGFloat = ${widgetLayout.metricLine}
    static let supportingRow: CGFloat = ${widgetLayout.supportingRow}
    static let supportingRowCaptioned: CGFloat = ${widgetLayout.supportingRowCaptioned}
    static let insightGlyph: CGFloat = ${widgetLayout.insightGlyph}
  }

  enum TypeScale {
    static let hero: CGFloat = ${widgetType.hero}
    static let metric: CGFloat = ${widgetType.metric}
    static let value: CGFloat = ${widgetType.value}
    static let label: CGFloat = ${widgetType.label}
    static let caption: CGFloat = ${widgetType.caption}
    static let floor: CGFloat = ${widgetType.floor}
  }

  /// One step of the type scale: its size at the default text size and the text style it
  /// grows with at a larger one.
  enum TypeStep: CaseIterable {
${STEPS.map((k) => `    case ${k}`).join('\n')}

    var size: CGFloat {
      switch self {
${STEPS.map((k) => `      case .${k}: return TypeScale.${k}`).join('\n')}
      }
    }

    var style: Font.TextStyle {
      switch self {
${STEPS.map((k) => `      case .${k}: return .${widgetTextScale.styles[k]}`).join('\n')}
      }
    }
  }

  /// The face every widget line draws, by the PostScript name of the bundled file for each
  /// weight. The extension's Info.plist lists the files; a name iOS cannot find draws the system
  /// face.
  enum Face {
    static let regular = "${widgetFace.regular.postScript}"
    static let semibold = "${widgetFace.semibold.postScript}"
    static let bold = "${widgetFace.bold.postScript}"
  }

  /// The most a figure, a label or a caption grows over its step's default size, whatever text
  /// size the reader picks. A line of prose is not held to it.
  static let maxTextScale: CGFloat = ${widgetTextScale.maxScale}

  enum Chart {
    static let fatigueDash: [CGFloat] = [${widgetChart.fatigueDash.join(', ')}]
    static let bandOpacity: Double = ${widgetChart.bandOpacity}
    static let bandAccentedOpacities: [Double] = [${widgetChart.bandAccentedOpacities.join(', ')}]
    static let bandBoundary: CGFloat = ${widgetChart.bandBoundary}
  }

  enum Body {
    static let accentedOpacities: [Double] = [${widgetBody.accentedOpacities.join(', ')}]
    static let accentedUntrainedOpacity: Double = ${widgetBody.accentedUntrainedOpacity}
    static let accentedOutline: CGFloat = ${widgetBody.accentedOutline}
  }
}
`;
}

// The ramp is one resource per shade, numbered as the shade it draws (1 to 5).
function androidColors(p: WidgetPalette): string {
  return [
    ...PALETTE_KEYS.map((k) => `  <color name="widget_${snake(k)}">${androidHex(p[k])}</color>`),
    ...p.strengthRamp.map(
      (hex, i) => `  <color name="widget_strength_ramp_${i + 1}">${androidHex(hex)}</color>`
    ),
  ].join('\n');
}

