#!/usr/bin/env node
// Refuse an export, a barrel line or a star line that nothing reaches.
//
// A name is reached when an import, a namespace import, a require(), a dynamic
// import() or an import type names it, and a test's import counts like any other.
// A re-export line is reached when a name it forwards is reached through it, so a
// barrel line that no importer goes through is named, and so is the export it
// forwards to when that export is reached only by way of the line. A star
// re-export is reached when a name it could forward is reached through it.
//
// Reachability is by file and name, resolved through the module graph, so a name
// shared by two modules is judged separately for each. A test's own exports are
// not judged: a test is a consumer.
//
// Only the modules the app builds are judged: src/ and modules/*/src/, not the
// generated bindings, not src/app/ (Expo Router reads route exports by convention),
// and not test or mock directories. Consumers are every tracked TypeScript or
// JavaScript file in src/, modules/, scripts/, config/ and web/.
//
// An export that must stay without a reader goes in ALLOWLIST with its reason, as
// `path#name`. An entry whose export is gone or reached fails the run, so no
// exemption outlives its reason.
//
// Usage: node scripts/lint-unused-exports.mjs [--root DIR]

import { posix } from 'node:path';

import ts from 'typescript';

import { indexedSources, refuseEmptyListing } from './lib/indexedSources.mjs';

const flag = process.argv.indexOf('--root');
const root = flag < 0 ? process.cwd() : process.argv[flag + 1];

const WILDCARD = '*';

// Deliberate exceptions. Each entry needs a reason, and the rule stays as it is.
const ALLOWLIST = new Map([
  [
    'modules/veloqrs/src/NativeVeloqrs.ts#Spec',
    'generated by uniffi-bindgen-react-native, and the React Native codegen reads the exported Spec interface',
  ],
  [
    'src/features/routes/screens/DetailCardStack.tsx#DETAIL_CARDS',
    'no reader in the tree; kept until the owner decides whether the detail card registry stays',
  ],
  [
    'src/features/routes/components/preview/PreviewMapView.tsx#RetiredLayerProps',
    'public props type of the retired map layer, kept until the owner decides it goes',
  ],
  [
    'src/features/routes/components/index.ts#RetiredLayerProps',
    'public props type of the retired map layer, kept until the owner decides it goes',
  ],
  [
    'src/features/routes/index.ts#RetiredLayerProps',
    'public props type of the retired map layer, kept until the owner decides it goes',
  ],
]);

const sources = indexedSources(root, [
  'src',
  'modules',
  'scripts',
  'config',
  'web',
  '*.js',
  '*.mjs',
  '*.ts',
  ':(exclude)modules/*/rust',
]);
refuseEmptyListing(sources, 'unused exports');

const CODE = /\.(?:ts|tsx|js|jsx|mjs|cjs)$/;
const parsed = new Map();
for (const [path, bytes] of sources) {
  if (!CODE.test(path) || path.endsWith('.d.ts')) continue;
  const kind = /\.tsx$/.test(path)
    ? ts.ScriptKind.TSX
    : /\.jsx$/.test(path)
      ? ts.ScriptKind.JSX
      : /\.(?:js|mjs|cjs)$/.test(path)
        ? ts.ScriptKind.JS
        : ts.ScriptKind.TS;
  parsed.set(
    path,
    ts.createSourceFile(path, bytes.toString('utf8'), ts.ScriptTarget.Latest, true, kind)
  );
}

const isFlaggable = (path) =>
  (path.startsWith('src/') || /^modules\/[^/]+\/src\//.test(path)) &&
  !/(^|\/)(__tests__|__mocks__|generated)\//.test(path) &&
  !path.startsWith('src/app/') &&
  !/\.(?:test|spec)\.tsx?$/.test(path);

const EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx', '.mjs'];
const INDEXES = ['/index.ts', '/index.tsx', '/index.js'];

// The package the app imports by name, which resolves through node_modules to this module.
const PACKAGE_MAIN = new Map([['veloqrs', 'modules/veloqrs/src/index.ts']]);

function resolveSpec(spec, from) {
  if (PACKAGE_MAIN.has(spec))
    return parsed.has(PACKAGE_MAIN.get(spec)) ? PACKAGE_MAIN.get(spec) : null;
  let base;
  if (spec.startsWith('@/')) base = `src/${spec.slice(2)}`;
  else if (spec.startsWith('.')) base = posix.normalize(posix.join(posix.dirname(from), spec));
  else return null;
  const stems = base.endsWith('.js')
    ? [`${base.slice(0, -3)}.ts`, `${base.slice(0, -3)}.tsx`, base]
    : [];
  const candidates = [base, ...EXTENSIONS.map((e) => base + e), ...INDEXES.map((i) => base + i)];
  return [...stems, ...candidates].find((c) => parsed.has(c)) ?? null;
}

const hasModifier = (node, kind) => node.modifiers?.some((m) => m.kind === kind) ?? false;
const lineOf = (sf, node) => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;

function bindingNames(name, out) {
  if (ts.isIdentifier(name)) out.push(name.text);
  else for (const el of name.elements) if (!ts.isOmittedExpression(el)) bindingNames(el.name, out);
  return out;
}

// Per file: `exports` maps an exported name to one entry, `stars` lists the
// `export * from` lines. An entry is a declaration (`decl`) or a forward to
// another file's name (`forward`), which covers a re-export line, a local
// `export { x }` of an import, and `export * as ns from`.
const models = new Map();

function modelOf(path, sf) {
  const exports = new Map();
  const stars = [];
  const bindings = new Map();

  for (const stmt of sf.statements) {
    if (!ts.isImportDeclaration(stmt) || !ts.isStringLiteral(stmt.moduleSpecifier)) continue;
    const target = resolveSpec(stmt.moduleSpecifier.text, path);
    if (!target || !stmt.importClause) continue;
    if (stmt.importClause.name)
      bindings.set(stmt.importClause.name.text, { target, importedName: 'default' });
    const named = stmt.importClause.namedBindings;
    if (named && ts.isNamespaceImport(named))
      bindings.set(named.name.text, { target, importedName: WILDCARD });
    else if (named)
      for (const el of named.elements)
        bindings.set(el.name.text, { target, importedName: (el.propertyName ?? el.name).text });
  }

  for (const stmt of sf.statements) {
    const line = lineOf(sf, stmt);
    if (ts.isExportAssignment(stmt) && !stmt.isExportEquals) {
      exports.set('default', { kind: 'decl', line });
    } else if (
      (ts.isVariableStatement(stmt) ||
        ts.isFunctionDeclaration(stmt) ||
        ts.isClassDeclaration(stmt) ||
        ts.isInterfaceDeclaration(stmt) ||
        ts.isTypeAliasDeclaration(stmt) ||
        ts.isEnumDeclaration(stmt) ||
        ts.isModuleDeclaration(stmt)) &&
      hasModifier(stmt, ts.SyntaxKind.ExportKeyword)
    ) {
      if (hasModifier(stmt, ts.SyntaxKind.DefaultKeyword)) {
        exports.set('default', { kind: 'decl', line });
      } else if (ts.isVariableStatement(stmt)) {
        for (const decl of stmt.declarationList.declarations)
          for (const name of bindingNames(decl.name, []))
            exports.set(name, { kind: 'decl', line: lineOf(sf, decl) });
      } else if (stmt.name && ts.isIdentifier(stmt.name)) {
        exports.set(stmt.name.text, { kind: 'decl', line });
      }
    } else if (ts.isExportDeclaration(stmt) && !stmt.moduleSpecifier) {
      if (!stmt.exportClause || !ts.isNamedExports(stmt.exportClause)) continue;
      for (const el of stmt.exportClause.elements) {
        const local = (el.propertyName ?? el.name).text;
        const exported = el.name.text;
        const binding = bindings.get(local);
        if (binding)
          exports.set(exported, {
            kind: 'forward',
            target: binding.target,
            importedName: binding.importedName,
            line,
          });
        else exports.set(exported, { kind: 'decl', line });
      }
    } else if (ts.isExportDeclaration(stmt) && ts.isStringLiteral(stmt.moduleSpecifier)) {
      const target = resolveSpec(stmt.moduleSpecifier.text, path);
      if (!target) continue;
      if (!stmt.exportClause) {
        stars.push({ target, spec: stmt.moduleSpecifier.text, line });
      } else if (ts.isNamespaceExport(stmt.exportClause)) {
        exports.set(stmt.exportClause.name.text, {
          kind: 'forward',
          target,
          importedName: WILDCARD,
          line,
        });
      } else {
        for (const el of stmt.exportClause.elements)
          exports.set(el.name.text, {
            kind: 'forward',
            target,
            importedName: (el.propertyName ?? el.name).text,
            line,
          });
      }
    }
  }
  return { exports, stars };
}

for (const [path, sf] of parsed) models.set(path, modelOf(path, sf));

// Demand: the names other files reach. `used` holds the forwards and stars that
// carried a demand, so a line that carried none is named.
const demanded = new Set();
const wildcard = new Set();
const used = new Set();
const surfaces = new Map();

function surfaceOf(path, seen = new Set()) {
  if (surfaces.has(path)) return surfaces.get(path);
  const m = models.get(path);
  const names = new Set();
  if (!m || seen.has(path)) return names;
  seen.add(path);
  for (const name of m.exports.keys()) names.add(name);
  for (const s of m.stars)
    for (const n of surfaceOf(s.target, seen)) if (n !== 'default') names.add(n);
  surfaces.set(path, names);
  return names;
}

function demand(path, name) {
  if (name === WILDCARD) return demandAll(path);
  if (wildcard.has(path)) return;
  demandName(path, name);
}

function demandName(path, name) {
  const key = `${path}\0${name}`;
  if (demanded.has(key)) return;
  demanded.add(key);
  const m = models.get(path);
  if (!m) return;
  const entry = m.exports.get(name);
  if (entry) {
    if (entry.kind === 'forward') {
      used.add(entry);
      demand(entry.target, entry.importedName);
    }
    return;
  }
  if (name === 'default') return;
  for (const s of m.stars) {
    if (!surfaceOf(s.target).has(name)) continue;
    used.add(s);
    demand(s.target, name);
  }
}

function demandAll(path) {
  if (wildcard.has(path)) return;
  wildcard.add(path);
  const m = models.get(path);
  if (!m) return;
  for (const name of m.exports.keys()) demandName(path, name);
  for (const s of m.stars) {
    used.add(s);
    demand(s.target, WILDCARD);
  }
}

// Every import, namespace import, require(), import() and import type that names
// a file is a demand on it. A `jest.mock` factory is not: it names no export.
for (const [path, sf] of parsed) {
  const visit = (node) => {
    if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
      const target = resolveSpec(node.moduleSpecifier.text, path);
      const clause = node.importClause;
      if (target && clause) {
        if (clause.name) demand(target, 'default');
        const named = clause.namedBindings;
        if (named && ts.isNamespaceImport(named)) demand(target, WILDCARD);
        else if (named)
          for (const el of named.elements) demand(target, (el.propertyName ?? el.name).text);
      }
    } else if (
      ts.isImportEqualsDeclaration(node) &&
      ts.isExternalModuleReference(node.moduleReference)
    ) {
      const expr = node.moduleReference.expression;
      const target = ts.isStringLiteral(expr) ? resolveSpec(expr.text, path) : null;
      if (target) demand(target, WILDCARD);
    } else if (
      ts.isCallExpression(node) &&
      node.arguments.length > 0 &&
      ts.isStringLiteralLike(node.arguments[0]) &&
      (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
        (ts.isIdentifier(node.expression) && node.expression.text === 'require') ||
        (ts.isPropertyAccessExpression(node.expression) &&
          node.expression.name.text === 'requireActual'))
    ) {
      const target = resolveSpec(node.arguments[0].text, path);
      if (target) demand(target, WILDCARD);
    } else if (
      ts.isImportTypeNode(node) &&
      ts.isLiteralTypeNode(node.argument) &&
      ts.isStringLiteral(node.argument.literal)
    ) {
      const target = resolveSpec(node.argument.literal.text, path);
      if (target) {
        let head = node.qualifier;
        while (head && ts.isQualifiedName(head)) head = head.left;
        demand(target, head ? head.text : WILDCARD);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

const isDemanded = (path, name) => wildcard.has(path) || demanded.has(`${path}\0${name}`);

const flagged = [];
const exportCount = { total: 0 };
for (const [path, m] of models) {
  if (!isFlaggable(path)) continue;
  for (const [name, entry] of m.exports) {
    exportCount.total += 1;
    const unreached = entry.kind === 'decl' ? !isDemanded(path, name) : !used.has(entry);
    if (unreached) flagged.push({ path, line: entry.line, name, key: `${path}#${name}` });
  }
  for (const s of m.stars) {
    exportCount.total += 1;
    if (!used.has(s))
      flagged.push({ path, line: s.line, name: `export * from '${s.spec}'`, key: null });
  }
}

// The allowlist describes this repository. A `--root` fixture is another tree, so its
// run does not judge the entries against it.
const flaggedKeys = new Set(flagged.map((f) => f.key).filter(Boolean));
const stale = flag < 0 ? [...ALLOWLIST.keys()].filter((key) => !flaggedKeys.has(key)) : [];
const unexempt = flagged.filter((f) => !(f.key && ALLOWLIST.has(f.key)));

if (stale.length > 0) {
  console.error('Stale ALLOWLIST entries (the export is gone or now reached):');
  for (const key of stale) console.error(`  ${key}`);
  console.error('');
  console.error('Fix: delete the entry from ALLOWLIST in this script.');
  process.exit(1);
}

if (unexempt.length > 0) {
  unexempt.sort((a, b) => (a.path === b.path ? a.line - b.line : a.path < b.path ? -1 : 1));
  console.error('Exports, barrel lines and star lines that nothing reaches:');
  for (const f of unexempt) console.error(`  ${f.path}:${f.line} ${f.name}`);
  console.error('');
  console.error('Fix: remove the export keyword, the barrel line or the star line. A name a');
  console.error('     test imports is reached and is not listed. An export that must stay');
  console.error('     without a reader goes in ALLOWLIST with its reason.');
  process.exit(1);
}

console.log('unused-exports: OK');
console.log(
  `  modules checked: ${[...models.keys()].filter(isFlaggable).length}, exports and lines checked: ${exportCount.total}, allowlisted: ${ALLOWLIST.size}`
);
