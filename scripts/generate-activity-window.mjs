#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';

import { trackedText } from './lib/indexedSources.mjs';

const root = process.cwd();
const check = process.argv.includes('--check');
const sourcePath = 'modules/veloqrs/rust/veloqrs/src/objects/sync.rs';
const source = check ? (trackedText(root, sourcePath) ?? '') : readFileSync(sourcePath, 'utf8');
const match = source.match(/const ACTIVITY_DAYS: i64 = (\d+);/);
if (!match) throw new Error('ACTIVITY_DAYS is missing from Rust sync');

const output = `// Generated by scripts/generate-activity-window.mjs. Do not edit.\nexport const DEFAULT_ACTIVITY_DAYS = ${match[1]};\n`;
const path = 'src/shared/native/activityWindow.generated.ts';
if (check) {
  if (trackedText(root, path) !== output) {
    throw new Error(`${path} differs from the Rust activity window`);
  }
} else {
  writeFileSync(path, output);
}
