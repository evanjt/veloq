#!/usr/bin/env node
// Write the Swift package that draws every iOS widget on a simulator.
//
// The widget extension builds only inside the app's Xcode project, which a
// prebuild writes, so the capture test runs from a package of its own instead:
// the extension's sources as the plugin writes them for the app, the capture
// test from `widget/ios/tests/`, and the snapshot fixtures the engine
// composes. `scripts/widget-captures-ios.sh` runs it, and every other test
// under `widget/ios/tests/` with it.

import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const PACKAGE = `// swift-tools-version:5.9
// Generated by scripts/write-widget-capture-package.mjs. Do not edit.
import PackageDescription

let package = Package(
  name: "WidgetCaptures",
  platforms: [.iOS("16.4")],
  targets: [
    .target(name: "VeloqWidget", path: "Sources/VeloqWidget"),
    .testTarget(
      name: "WidgetCaptureTests",
      dependencies: ["VeloqWidget"],
      path: "Tests/WidgetCaptureTests",
      resources: [.copy("fixtures")]),
  ]
)
`;

const FIXTURES = ['demo.json', 'empty.json', 'long-text.json', 'no-wellness.json'];

export function writeWidgetCapturePackage(out) {
  const plugin = require(join(root, 'src', 'plugins', 'with-ios-widget.js'));
  rmSync(out, { recursive: true, force: true });
  const sources = join(out, 'Sources');
  plugin.writeWidgetFiles(root, sources, 'App');
  rmSync(join(sources, 'App'), { recursive: true, force: true });
  const widget = join(sources, 'VeloqWidget');
  plugin.writeWidgetBundles(widget, plugin.INCLUDE_RECORD_WIDGET);
  // A package compiles Swift alone: the plist, the entitlements, the bridging
  // header and the string catalogue belong to the app's target.
  for (const name of readdirSync(widget)) {
    if (!name.endsWith('.swift')) rmSync(join(widget, name), { recursive: true, force: true });
  }

  // The extension's entry point would be the test bundle's too.
  const launcher = join(widget, 'VeloqWidget.swift');
  const swift = readFileSync(launcher, 'utf8');
  const entries = swift.match(/^@main\n/gm) ?? [];
  if (entries.length !== 1) {
    throw new Error(`write-widget-capture-package: expected one @main in ${launcher}`);
  }
  writeFileSync(launcher, swift.replace(/^@main\n/m, ''));

  const tests = join(out, 'Tests', 'WidgetCaptureTests');
  mkdirSync(join(tests, 'fixtures'), { recursive: true });
  const testSources = join(root, 'widget', 'ios', 'tests');
  for (const name of readdirSync(testSources).filter((file) => file.endsWith('.swift'))) {
    copyFileSync(join(testSources, name), join(tests, name));
  }
  for (const name of FIXTURES) {
    copyFileSync(join(root, 'widget', 'fixtures', name), join(tests, 'fixtures', name));
  }
  writeFileSync(join(out, 'Package.swift'), PACKAGE);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf('--out');
  const out = at === -1 ? undefined : process.argv[at + 1];
  if (!out) {
    console.error('write-widget-capture-package: --out is required');
    process.exit(1);
  }
  writeWidgetCapturePackage(resolve(out));
}
