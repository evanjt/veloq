#!/usr/bin/env node

// Regenerates the bundled MapLibre GL JS renderer. Every map in the app is a
// WebView, and the page used to pull the renderer off unpkg at open time, so a
// device with no radio and a cold WebView HTTP cache drew no map at all (B131,
// decided in Q28).
//
// The renderer has to be defined before the first line that touches
// `maplibregl`, which is before the `bundledAssetRequest` postMessage channel
// exists, so it cannot come through that channel like the sprite and the
// glyphs do. It is inlined into the HTML string instead, in `mapLibreHead`,
// the one place all three page builders share.
//
// The bytes are written as a TypeScript module rather than a binary asset for
// the same reason the basemap assets are: a required module works the same in
// dev, release and Jest, with no expo-asset and no metro assetExts entry.
//
// The version is pinned here and asserted by the tests, so a renderer bump is
// a deliberate commit rather than whatever unpkg served that day.

import { writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VERSION = '5.19.0';
const ORIGIN = `https://unpkg.com/maplibre-gl@${VERSION}/dist`;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/features/maps/assets');

async function fetchText(file) {
  const url = `${ORIGIN}/${file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const text = await response.text();
  if (text.length === 0) throw new Error(`${url}: empty`);
  return text;
}

// A `</script` anywhere in the source would close the tag it is inlined into.
// Neutralised here rather than per page build, which would rescan a megabyte
// every time a map opens.
const forInlining = (text) => text.replace(/<\/script/gi, '<\\/script');

const sha = (text) => createHash('sha256').update(text).digest('hex');

async function main() {
  mkdirSync(outDir, { recursive: true });

  const js = await fetchText('maplibre-gl.js');
  const css = await fetchText('maplibre-gl.css');

  const header = `// Generated by scripts/fetch-maplibre-renderer.mjs. Do not edit.
// Source: ${ORIGIN}. MapLibre GL JS ${VERSION}, 3-Clause BSD.
// sha256 maplibre-gl.js  ${sha(js)}
// sha256 maplibre-gl.css ${sha(css)}
`;

  writeFileSync(
    join(outDir, 'maplibreRenderer.generated.ts'),
    `${header}
export const MAPLIBRE_GL_VERSION = '${VERSION}';

export const MAPLIBRE_GL_JS = ${JSON.stringify(forInlining(js))};

export const MAPLIBRE_GL_CSS = ${JSON.stringify(css)};
`
  );

  console.log(`maplibre-gl ${VERSION}: ${js.length} B js, ${css.length} B css`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
