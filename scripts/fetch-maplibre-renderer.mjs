#!/usr/bin/env node

// Regenerates the bundled MapLibre GL JS renderer. Every map in the app is a
// WebView, and the page used to pull the renderer off unpkg at open time, so a
// device with no radio and a cold WebView HTTP cache drew no map at all.
//
// The renderer and its stylesheet ship as files under the basemap assets, which
// Android packages as its assets and the podspec copies into the iOS resource
// bundle. `mapLibreHead` names them on the page's own origin under
// `veloq-asset/`, where the platform interceptor answers them out of the app,
// so no page string carries a megabyte of renderer and every page shares one
// file rather than holding its own copy on the JavaScript heap.
//
// The file name carries the version, so the interceptor can let the WebView
// keep it for good: a bump is a new name, never a stale answer. The directory
// is emptied first so only the pinned version ships.
//
// The version is pinned here and asserted by the tests, and the sha256 of
// each file is written into the generated module, where a contract test checks
// the shipped bytes against it, so a renderer bump is a deliberate commit
// rather than whatever unpkg served that day. A bump is judged by
// `npm run test:map-pages`, which draws every page with it in a headless
// Chromium, and by check-maplibre-attribution.mjs.

import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VERSION = '5.19.0';
const ORIGIN = `https://unpkg.com/maplibre-gl@${VERSION}/dist`;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const moduleDir = join(root, 'src/features/maps/assets');
const RENDERER_DIR = 'renderer';
const assetDir = join(root, 'modules/veloqrs/assets/basemap', RENDERER_DIR);

async function fetchText(file) {
  const url = `${ORIGIN}/${file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const text = await response.text();
  if (text.length === 0) throw new Error(`${url}: empty`);
  return text;
}

const sha = (text) => createHash('sha256').update(text).digest('hex');

async function main() {
  const js = await fetchText('maplibre-gl.js');
  const css = await fetchText('maplibre-gl.css');

  const jsFile = `${RENDERER_DIR}/maplibre-gl-${VERSION}.js`;
  const cssFile = `${RENDERER_DIR}/maplibre-gl-${VERSION}.css`;

  rmSync(assetDir, { recursive: true, force: true });
  mkdirSync(assetDir, { recursive: true });
  writeFileSync(join(assetDir, `maplibre-gl-${VERSION}.js`), js);
  writeFileSync(join(assetDir, `maplibre-gl-${VERSION}.css`), css);

  mkdirSync(moduleDir, { recursive: true });
  writeFileSync(
    join(moduleDir, 'maplibreRenderer.generated.ts'),
    `// Generated by scripts/fetch-maplibre-renderer.mjs. Do not edit.
// Source: ${ORIGIN}. MapLibre GL JS ${VERSION}, 3-Clause BSD.

export const MAPLIBRE_GL_VERSION = '${VERSION}';

/** The renderer under the basemap assets, as the page asks for it after \`veloq-asset/\`. */
export const MAPLIBRE_GL_JS_FILE = '${jsFile}';

/** The renderer's stylesheet, beside it. */
export const MAPLIBRE_GL_CSS_FILE = '${cssFile}';

export const MAPLIBRE_GL_JS_SHA256 = '${sha(js)}';

export const MAPLIBRE_GL_CSS_SHA256 = '${sha(css)}';
`
  );

  console.log(`maplibre-gl ${VERSION}: ${js.length} B js, ${css.length} B css`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
