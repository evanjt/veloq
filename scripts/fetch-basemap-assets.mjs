#!/usr/bin/env node

// Regenerates the bundled basemap assets. The sprite and the Latin glyph
// ranges are byte-identical for every install and a map without them draws no
// icons and no labels, so they ship in the app rather than being fetched once
// per device (B116, decided in Q67).
//
// The bytes are written as base64 TypeScript modules rather than as binary
// assets: reading a binary asset back needs expo-asset and a metro assetExts
// entry, and a required module works the same in dev, release and Jest.
//
// The glyph set is deliberately partial. Every range of the three stacks is
// 104 MB, which is CJK. The ranges below are 1.7 MB and cover Latin, Latin
// Extended Additional and General Punctuation. Everything else stays on the
// network and degrades to a box offline.

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/features/maps/assets');

const ORIGIN = 'https://tiles.openfreemap.org';
const SPRITE_DIR = 'sprites/ofm_f384';
const SPRITE_FILES = ['ofm.json', 'ofm.png', 'ofm@2x.json', 'ofm@2x.png'];
const STACKS = ['Noto Sans Regular', 'Noto Sans Bold', 'Noto Sans Italic'];
const RANGES = ['0-255', '256-511', '512-767', '768-1023', '7680-7935', '8192-8447'];

const HEADER = `// Generated by scripts/fetch-basemap-assets.mjs. Do not edit.
// Source: ${ORIGIN}. OpenMapTiles sprite (MIT), Noto Sans (SIL OFL 1.1).
`;

async function fetchBase64(path) {
  const url = `${ORIGIN}/${path}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length === 0) throw new Error(`${url}: empty`);
  return bytes.toString('base64');
}

function writeModule(name, constant, entries) {
  const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: '${value}',`).join('\n');
  writeFileSync(
    join(outDir, name),
    `${HEADER}\nexport const ${constant}: Record<string, string> = {\n${body}\n};\n`
  );
}

const slug = (stack) => stack.replace(/[^A-Za-z]/g, '');

async function main() {
  mkdirSync(outDir, { recursive: true });

  const sprite = [];
  for (const file of SPRITE_FILES) {
    sprite.push([file, await fetchBase64(`${SPRITE_DIR}/${file}`)]);
  }
  writeModule('basemapSprite.generated.ts', 'BASEMAP_SPRITE', sprite);

  for (const stack of STACKS) {
    const ranges = [];
    for (const range of RANGES) {
      ranges.push([range, await fetchBase64(`fonts/${encodeURIComponent(stack)}/${range}.pbf`)]);
    }
    writeModule(`basemapGlyphs${slug(stack)}.generated.ts`, `BASEMAP_GLYPHS_${slug(stack).toUpperCase()}`, ranges);
  }

  const total = [...sprite].reduce((n, [, b64]) => n + Buffer.from(b64, 'base64').length, 0);
  console.log(`sprite ${total} B, ${STACKS.length} stacks x ${RANGES.length} ranges written`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
