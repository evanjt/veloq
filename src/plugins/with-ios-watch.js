const { withDangerousMod, withXcodeProject } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");
const plist = require("@expo/plist").default;

const { copyDir } = require("./with-ios-push-extension");
const {
  addMissingResources,
  addMissingSourceFiles,
  targetUuidByName,
} = require("./with-ios-widget");
const { ensureTargetDependencySections } = require("./xcodeTargetDependency");
const { targetBuildSettings } = require("./xcodeEngineLink");

/**
 * Injects the watchOS companion app during prebuild, the way
 * `with-ios-widget.js` injects the WidgetKit extension. The native dirs are
 * gitignored and regenerated by `expo prebuild`, so the Swift, the Info.plist
 * and the asset catalogue live in the tracked `watch/ios/VeloqWatch/` tree and
 * are copied into `ios/` here.
 *
 * The watch app is a single-target SwiftUI app: an `application` product with
 * `SDKROOT = watchos`, not the two-target layout (a WatchKit app plus a
 * WatchKit extension) the `xcode` package writes for `watch2_app`. It is
 * embedded in the iPhone app under `Watch/`, and the Info.plist names the
 * iPhone app as its companion, so the watch app installs with it and does not
 * run without it.
 *
 * It opens no App Group and no keychain: WatchConnectivity needs no
 * entitlement, and what the watch shows is what the phone sent it.
 */

const TARGET = "VeloqWatch";
const SOURCE_DIR = path.join("watch", "ios", TARGET);
const EMBED_PHASE = "Embed Watch Content";
const EMBED_DESTINATION = '"$(CONTENTS_FOLDER_PATH)/Watch"';
const ASSET_CATALOGUE = "Assets.xcassets";
const ASSET_CATALOGUE_TYPE = "folder.assetcatalog";

const unquote = (value) => String(value ?? "").replace(/^"|"$/g, "");

/** The bundle id of the watch app, which watchOS requires to extend the iPhone app's. */
function watchBundleId(appBundleId) {
  return `${appBundleId}.watchkitapp`;
}

/** Every Swift file the watch app compiles, read from the tracked tree. */
function watchSwiftFiles(projectRoot) {
  return fs
    .readdirSync(path.join(projectRoot, SOURCE_DIR))
    .filter((f) => f.endsWith(".swift"))
    .sort();
}

/**
 * Copy the tracked tree into `ios/` and write the companion bundle id into the
 * Info.plist, which the tracked copy cannot know: it is the iPhone app's id,
 * and that differs between the development and the store builds.
 */
function writeWatchFiles(projectRoot, platformProjectRoot, appBundleId) {
  const dest = path.join(platformProjectRoot, TARGET);
  copyDir(path.join(projectRoot, SOURCE_DIR), dest);

  const infoPath = path.join(dest, "Info.plist");
  const info = plist.parse(fs.readFileSync(infoPath, "utf8"));
  info.WKCompanionAppBundleIdentifier = appBundleId;
  fs.writeFileSync(infoPath, plist.build(info));
}

function withWatchFiles(config) {
  return withDangerousMod(config, [
    "ios",
    (cfg) => {
      writeWatchFiles(
        cfg.modRequest.projectRoot,
        cfg.modRequest.platformProjectRoot,
        cfg.ios?.bundleIdentifier || "com.veloq.app"
      );
      return cfg;
    },
  ]);
}

/**
 * The watch target's own build settings. Everything not named here it inherits
 * from the project, which is where the pod install writes settings meant for
 * the app.
 */
function applyWatchBuildSettings(settings, { version, buildNumber }) {
  settings.INFOPLIST_FILE = `"${TARGET}/Info.plist"`;
  settings.SDKROOT = "watchos";
  settings.SUPPORTED_PLATFORMS = '"watchsimulator watchos"';
  settings.WATCHOS_DEPLOYMENT_TARGET = '"10.0"';
  // 4 is the watch. The project's iOS deployment target means nothing for this
  // SDK, and an inherited one is read as a conflicting platform.
  settings.TARGETED_DEVICE_FAMILY = '"4"';
  delete settings.IPHONEOS_DEPLOYMENT_TARGET;
  settings.LD_RUNPATH_SEARCH_PATHS = '"$(inherited) @executable_path/Frameworks"';
  settings.ASSETCATALOG_COMPILER_APPICON_NAME = "AppIcon";
  settings.ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME = "AccentColor";
  settings.CODE_SIGN_STYLE = "Automatic";
  settings.SWIFT_VERSION = '"5.9"';
  settings.GENERATE_INFOPLIST_FILE = "NO";
  settings.CURRENT_PROJECT_VERSION = `"${buildNumber}"`;
  settings.MARKETING_VERSION = `"${version}"`;
  // `apple.ccacheEnabled` has the pod install write CC, LD, CXX and LDPLUSPLUS
  // across the whole project as `$(REACT_NATIVE_PATH)/scripts/xcode/...`, and
  // REACT_NATIVE_PATH resolves from PODS_ROOT, which only a pod target
  // carries. Give the watch target the same path from its own SRCROOT, as the
  // widget extension has.
  settings.REACT_NATIVE_PATH = '"$(SRCROOT)/../node_modules/react-native"';
}

/** Create the watch target, its phases and its group. */
function createWatchTarget(proj, appBundleId) {
  // `addTarget` makes the app target depend on this one itself, but only writes
  // it when both dependency sections already exist, and a generated project has
  // neither.
  ensureTargetDependencySections(proj);
  const target = proj.addTarget(TARGET, "application", TARGET, watchBundleId(appBundleId));

  proj.addBuildPhase([], "PBXSourcesBuildPhase", "Sources", target.uuid);
  proj.addBuildPhase([], "PBXResourcesBuildPhase", "Resources", target.uuid);
  proj.addBuildPhase([], "PBXFrameworksBuildPhase", "Frameworks", target.uuid);

  const group = proj.addPbxGroup([], TARGET, TARGET);
  proj.addToPbxGroup(group.uuid, proj.getFirstProject().firstProject.mainGroup);

  return target.uuid;
}

/**
 * The app target copies the watch app into `Watch/` of its own bundle, which is
 * where an iPhone app carries the watch app that installs with it. `addTarget`
 * writes that phase only for the two-target layout, so it is written here, and
 * on a target an earlier prebuild left without it.
 */
function ensureEmbedPhase(proj, watchUuid) {
  const appUuid = proj.getFirstTarget().uuid;
  const app = proj.pbxNativeTargetSection()[appUuid];
  if (app.buildPhases.some((phase) => unquote(phase.comment) === EMBED_PHASE)) return;

  const productRef = proj.pbxNativeTargetSection()[watchUuid].productReference;
  const builds = proj.pbxBuildFileSection();
  const buildKey = Object.keys(builds).find(
    (key) => !key.endsWith("_comment") && builds[key].fileRef === productRef
  );
  const comment = `${TARGET}.app in ${EMBED_PHASE}`;
  builds[buildKey].settings = { ATTRIBUTES: ["RemoveHeadersOnCopy"] };
  builds[`${buildKey}_comment`] = comment;

  const { buildPhase } = proj.addBuildPhase(
    [],
    "PBXCopyFilesBuildPhase",
    EMBED_PHASE,
    appUuid,
    "watch2_app",
    EMBED_DESTINATION
  );
  buildPhase.files.push({ value: buildKey, comment });
}

/** The app target depends on the watch target, so the embedded product is built first. */
function ensureAppDependency(proj, watchUuid) {
  const appUuid = proj.getFirstTarget().uuid;
  const app = proj.pbxNativeTargetSection()[appUuid];
  const dependencies = proj.hash.project.objects.PBXTargetDependency ?? {};
  const present = app.dependencies.some((entry) => dependencies[entry.value]?.target === watchUuid);
  if (!present) {
    ensureTargetDependencySections(proj);
    proj.addTargetDependency(appUuid, [watchUuid]);
  }
}

/**
 * Wire the watch target to the sources it compiles, creating it when the
 * project has none. The target survives every prebuild after the first, so its
 * sources, its embed phase and its settings are reconciled either way: a file
 * added to `watch/ios` is otherwise copied into `ios/` and then never compiled.
 */
function configureWatchProject(proj, { swiftFiles, bundleId, version, buildNumber }) {
  const targetUuid = targetUuidByName(proj, TARGET) ?? createWatchTarget(proj, bundleId);
  addMissingSourceFiles(proj, targetUuid, swiftFiles, TARGET);
  addMissingResources(proj, targetUuid, [ASSET_CATALOGUE], TARGET, ASSET_CATALOGUE_TYPE);
  ensureAppDependency(proj, targetUuid);
  ensureEmbedPhase(proj, targetUuid);
  for (const settings of targetBuildSettings(proj, TARGET)) {
    applyWatchBuildSettings(settings, { version, buildNumber });
  }
}

function withWatchTarget(config) {
  return withXcodeProject(config, (cfg) => {
    configureWatchProject(cfg.modResults, {
      swiftFiles: watchSwiftFiles(cfg.modRequest.projectRoot),
      bundleId: cfg.ios?.bundleIdentifier || "com.veloq.app",
      version: cfg.version || "1.0.0",
      buildNumber: cfg.ios?.buildNumber || "1",
    });
    return cfg;
  });
}

module.exports = function withIosWatch(config) {
  config = withWatchFiles(config);
  config = withWatchTarget(config);
  return config;
};

module.exports.TARGET = TARGET;
module.exports.SOURCE_DIR = SOURCE_DIR;
module.exports.EMBED_PHASE = EMBED_PHASE;
module.exports.applyWatchBuildSettings = applyWatchBuildSettings;
module.exports.configureWatchProject = configureWatchProject;
module.exports.watchBundleId = watchBundleId;
module.exports.watchSwiftFiles = watchSwiftFiles;
module.exports.writeWatchFiles = writeWatchFiles;
