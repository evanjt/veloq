/**
 * Scenario: the Android and iOS widgets draw the body from two generated
 * sources, one Kotlin and one Swift. If the two emitters encoded a polygon
 * differently, or listed different parts, the two platforms would draw
 * different bodies and nothing would say so.
 *
 * Expected behaviour: for one polygon set both emitters carry the same parts in
 * the same order with the same encoded strings, and both carry the drawing
 * library's licence notice, since the outlines ship inside the app.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = join(__dirname, '../../..');
const SCRIPT = pathToFileURL(join(ROOT, 'scripts/generate-muscle-polygons.mjs')).href;

type Ring = [number, number][];
type Outlines = Record<'male' | 'female', Record<'front' | 'back', [string, Ring[]][]>>;

const triangle: Ring = [
  [0, 0],
  [1, 0],
  [0.5, 0.25],
];
const square: Ring = [
  [0.01, 0.02],
  [0.03, 0.02],
  [0.03, 0.04],
  [0.01, 0.04],
];

const OUTLINES: Outlines = {
  male: {
    front: [
      ['tail', [triangle]],
      ['left-wing', [square, triangle]],
    ],
    back: [['crest', [square]]],
  },
  female: {
    front: [['beak', [triangle]]],
    back: [
      ['crest', [square]],
      ['tail', [triangle, square]],
    ],
  },
};

function emitBoth(outlines: Outlines): { kotlin: string; swift: string } {
  const program = `
    const g = await import(${JSON.stringify(SCRIPT)});
    const outlines = JSON.parse(process.argv[1]);
    console.log(JSON.stringify({ kotlin: g.emitKotlin(outlines), swift: g.emitSwift(outlines) }));
  `;
  const out = execFileSync(
    'node',
    ['--input-type=module', '-e', program, JSON.stringify(outlines)],
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
  );
  return JSON.parse(out);
}

const SETS = ['maleFront', 'maleBack', 'femaleFront', 'femaleBack'] as const;

/** The (slug, encoded) pairs of each set, in the order each source lists them. */
function kotlinPairs(source: string): Record<string, [string, string][]> {
  const out: Record<string, [string, string][]> = {};
  for (const set of SETS) {
    const name = set.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase();
    const block = source.split(`private val ${name}: Array<Pair<String, String>> = arrayOf(`)[1];
    expect(block).toBeDefined();
    const body = block.slice(0, block.indexOf('\n  )'));
    out[set] = [...body.matchAll(/"([^"]+)" to "([^"]*)"/g)].map((m) => [m[1], m[2]]);
  }
  return out;
}

function swiftPairs(source: string): Record<string, [string, string][]> {
  const out: Record<string, [string, string][]> = {};
  for (const set of SETS) {
    const block = source.split(`private static let ${set}Encoded: [(String, String)] = [`)[1];
    expect(block).toBeDefined();
    const body = block.slice(0, block.indexOf('\n  ]'));
    out[set] = [...body.matchAll(/\("([^"]+)", "([^"]*)"\)/g)].map((m) => [m[1], m[2]]);
  }
  return out;
}

describe('the widget body outline emitters', () => {
  const { kotlin, swift } = emitBoth(OUTLINES);

  it('give both platforms the same parts and the same encoded polygons', () => {
    const k = kotlinPairs(kotlin);
    expect(k).toEqual(swiftPairs(swift));
    expect(k.maleFront.map(([slug]) => slug)).toEqual(['tail', 'left-wing']);
    expect(k.femaleBack.map(([slug]) => slug)).toEqual(['crest', 'tail']);
  });

  it('encode a ring as x y pairs in ten-thousandths, rings split by a semicolon', () => {
    const k = kotlinPairs(kotlin);
    expect(k.maleFront[1]).toEqual([
      'left-wing',
      '100 200 300 200 300 400 100 400;0 0 10000 0 5000 2500',
    ]);
  });

  it('carry the generated header and the drawing library licence in full', () => {
    const license = readFileSync(
      join(ROOT, 'node_modules/react-native-body-highlighter/LICENSE'),
      'utf8'
    );
    for (const source of [kotlin, swift]) {
      expect(source).toContain('GENERATED by scripts/generate-muscle-polygons.mjs. Do not edit.');
      for (const line of license.split('\n').filter((l) => l.trim() !== '')) {
        expect(source).toContain(`// ${line.trim()}`);
      }
    }
  });

  it('leave the Kotlin package for the widget plugin to fill', () => {
    expect(kotlin).toMatch(/^package __PKG__\.widget$/m);
  });

  it('agree between the committed Kotlin and Swift sources', () => {
    const committedKotlin = readFileSync(join(ROOT, 'widget/android/java/BodyOutline.kt'), 'utf8');
    const committedSwift = readFileSync(
      join(ROOT, 'widget/ios/VeloqWidget/BodyOutline.swift'),
      'utf8'
    );
    const k = kotlinPairs(committedKotlin);
    expect(k).toEqual(swiftPairs(committedSwift));
    for (const set of SETS) expect(k[set].length).toBeGreaterThan(0);
  });
});
