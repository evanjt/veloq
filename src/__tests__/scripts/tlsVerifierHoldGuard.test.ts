/**
 * Scenario: the engine's HTTP clients verify TLS against bundled roots and make
 * no JVM call. A reqwest release past the held line pulls the platform verifier
 * on every rustls path, and on Android that verifier needs a Kotlin component and
 * a JNI initialisation the engine does not have, so the build compiles and every
 * HTTPS request fails on the handset. Dependabot opens a pull request for each
 * cargo minor bump, and a 0.x minor step is exactly that release, so that pull
 * request fails every month.
 *
 * Expected behaviour: the guard fails when the workspace lockfile carries
 * rustls-platform-verifier, and when the cargo Dependabot entry stops ignoring
 * reqwest's minor updates. An ignore with no update types covers every update.
 */

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

const SCRIPT = join(__dirname, '../../../scripts/lint-tls-verifier-hold.mjs');
const LOCK = 'modules/veloqrs/rust/Cargo.lock';
const DEPENDABOT = '.github/dependabot.yml';

function lockfile(extra: string[] = []): string {
  const entries = [
    '# This file is automatically @generated by Cargo.',
    'version = 4',
    '',
    '[[package]]',
    'name = "reqwest"',
    'version = "0.12.28"',
    'dependencies = [',
    ' "rustls",',
    ' "webpki-roots",',
    ']',
    '',
    '[[package]]',
    'name = "rustls-platform-verifier-android"',
    'version = "0.1.1"',
    '',
    '[[package]]',
    'name = "webpki-roots"',
    'version = "1.0.8"',
    '',
  ];
  return [...entries, ...extra].join('\n');
}

const VERIFIER = ['[[package]]', 'name = "rustls-platform-verifier"', 'version = "0.7.1"', ''];

function dependabot(cargoIgnore: string[]): string {
  return [
    'version: 2',
    'updates:',
    '  - package-ecosystem: "npm"',
    '    directory: "/"',
    '    schedule:',
    '      interval: "monthly"',
    '    ignore:',
    '      - dependency-name: "reqwest"',
    '  - package-ecosystem: "cargo"',
    '    directory: "/modules/veloqrs/rust"',
    '    schedule:',
    '      interval: "monthly"',
    '    groups:',
    '      cargo-patch:',
    '        update-types: ["patch"]',
    ...(cargoIgnore.length > 0 ? ['    ignore:', ...cargoIgnore] : []),
    '',
  ].join('\n');
}

const HELD = [
  '      - dependency-name: "uniffi"',
  '      - dependency-name: "reqwest"',
  '        update-types: ["version-update:semver-minor"]',
];

const roots: string[] = [];

function fixture(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'tls-hold-'));
  roots.push(root);
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

function runGuard(root: string): { status: number; output: string } {
  try {
    const output = execFileSync('node', [SCRIPT, '--root', root], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { status: 0, output };
  } catch (error) {
    const e = error as { status: number; stdout?: string; stderr?: string };
    return { status: e.status, output: `${e.stdout ?? ''}${e.stderr ?? ''}` };
  }
}

afterAll(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

describe('lint-tls-verifier-hold', () => {
  it('passes on bundled roots with reqwest minor updates ignored', () => {
    expect(runGuard(fixture({ [LOCK]: lockfile(), [DEPENDABOT]: dependabot(HELD) })).status).toBe(
      0
    );
  });

  it('fails naming the verifier when the lockfile carries it', () => {
    const r = runGuard(fixture({ [LOCK]: lockfile(VERIFIER), [DEPENDABOT]: dependabot(HELD) }));
    expect(r.status).toBe(1);
    expect(r.output).toContain('rustls-platform-verifier');
  });

  it('fails when the cargo entry has no reqwest ignore, even with the npm entry holding one', () => {
    const r = runGuard(
      fixture({
        [LOCK]: lockfile(),
        [DEPENDABOT]: dependabot(['      - dependency-name: "uniffi"']),
      })
    );
    expect(r.status).toBe(1);
    expect(r.output).toContain('reqwest');
  });

  it('fails when the cargo entry has no ignore list at all', () => {
    const r = runGuard(fixture({ [LOCK]: lockfile(), [DEPENDABOT]: dependabot([]) }));
    expect(r.status).toBe(1);
    expect(r.output).toContain('reqwest');
  });

  it('fails when the reqwest ignore covers patch updates only', () => {
    const r = runGuard(
      fixture({
        [LOCK]: lockfile(),
        [DEPENDABOT]: dependabot([
          '      - dependency-name: "reqwest"',
          '        update-types: ["version-update:semver-patch"]',
        ]),
      })
    );
    expect(r.status).toBe(1);
    expect(r.output).toContain('semver-minor');
  });

  it('passes when the reqwest ignore names no update types, which ignores every update', () => {
    const root = fixture({
      [LOCK]: lockfile(),
      [DEPENDABOT]: dependabot(['      - dependency-name: "reqwest"']),
    });
    expect(runGuard(root).status).toBe(0);
  });

  it('fails rather than passing when either file is missing', () => {
    expect(runGuard(fixture({ [DEPENDABOT]: dependabot(HELD) })).status).toBe(1);
    expect(runGuard(fixture({ [LOCK]: lockfile() })).status).toBe(1);
  });
});
